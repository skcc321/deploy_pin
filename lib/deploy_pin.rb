# DeployPin runs one-off and recurring tasks around a deployment
# (for example, data migrations before or after the code is released).
#
# Tasks are plain Ruby files kept in {DeployPin.tasks_path}. Each one has a
# header with an identifier, a group and a title. Tasks run in group order,
# and each non-recurring task runs only once: its completion is stored in
# the configured {DeployPin.storage}.
#
# DeployPin works in Rails and in any other Ruby app. Configure it in the
# file generated by `deploy_pin install` (`config/deploy_pin.rb`), or by
# `rails g deploy_pin:install` in a Rails app (`config/initializers/deploy_pin.rb`).
#
# @example config/initializers/deploy_pin.rb
#   DeployPin.setup do
#     tasks_path 'lib/deploy_pin'
#     groups %w[pre I II III]
#     fallback_group 'III'
#     statement_timeout 10.minutes
#   end
#
# @!method self.continue_on_error(val = nil)
#   When true, a failing task is logged and the run moves on to the next task
#   instead of raising. Defaults to `false`.
#   @param val [Boolean, nil] new value; omit to read the current one
#   @return [Boolean]
#
# @!method self.deployment_state_transition(val = nil)
#   Enables tracking of the deployment state in Redis, exposed through
#   {DeploymentState#ongoing_deployment?} and {DeploymentState#pending_deployment?}.
#   @example
#     deployment_state_transition({
#       ongoing: %w[I III],   # groups that start and end the "ongoing" state
#       pending: 'rollback',  # group that sets the "pending" state
#       ttl: 20.seconds,      # how long to cache the state in memory
#       redis_url: 'redis://localhost:6379'
#     })
#   @param val [Hash, nil] new value; omit to read the current one
#   @return [Hash, nil]
#
# @!method self.fallback_group(val = nil)
#   Default group for `deploy_pin task` (`rails g deploy_pin:task`) when `--group` is not given.
#   @param val [String, nil] new value; omit to read the current one
#   @return [String, nil]
#
# @!method self.groups(val = nil)
#   Ordered list of task groups. Tasks run in this group order, and a task's
#   group must be one of these.
#   @param val [Array<String>, nil] new value; omit to read the current one
#   @return [Array<String>, nil]
#
# @!method self.list_formatter(val = nil)
#   Prints a task for `rake deploy_pin:list`.
#   @param val [Proc, nil] `->(index, task) { ... }`; omit to read the current one
#   @return [Proc, nil]
#
# @!method self.short_list_formatter(val = nil)
#   Prints a group of tasks for `rake deploy_pin:short_list`.
#   @param val [Proc, nil] `->(group, tasks, start_index) { ... }`; omit to read the current one
#   @return [Proc, nil]
#
# @!method self.run_formatter(val = nil)
#   Prints progress for `rake deploy_pin:run`. It is called once before a task
#   starts (`start` is true) and, for executable tasks, once after it finishes
#   with its `duration` in seconds.
#   @param val [Proc, nil] `->(index, task_count, task, executable, start, duration = nil) { ... }`;
#     omit to read the current one
#   @return [Proc, nil]
#
# @!method self.statement_timeout(val = nil)
#   Default database statement timeout for tasks and for
#   {Database.execute_with_timeout}. Requires ActiveRecord.
#   @param val [ActiveSupport::Duration, Numeric, nil] new value; omit to read the current one
#   @return [ActiveSupport::Duration, Numeric, nil]
#
# @!method self.storage(val = nil)
#   Where task records are stored: `:active_record` (default), `:mongoid`, or
#   a record class of your own.
#   @see Storage
#   @param val [Symbol, Class, nil] new value; omit to read the current one
#   @return [Symbol, Class]
#
# @!method self.task_wrapper(val = nil)
#   Wraps the execution of every task, for example to add logging or error
#   reporting. It must call `task_runner.call` to run the task.
#   @example
#     task_wrapper ->(task, task_runner) { Rails.logger.tagged(task.identifier) { task_runner.call } }
#   @param val [Proc, nil] `->(task, task_runner) { ... }`; omit to read the current one
#   @return [Proc]
#
# @!method self.test_framework(val = nil)
#   Test framework for the test file that `deploy_pin task` creates
#   next to each task; `false` turns test generation off. When not set, RSpec
#   is used if the `RSpec` constant is loaded (e.g. rspec-rails in the
#   `:development` group); otherwise no test is generated.
#   @see TaskGenerator::TEST_FRAMEWORKS
#   @param val [Symbol, false, nil] new value; omit to read the current one
#   @return [Symbol, false, nil]
#
# @!method self.tests_path(val = nil)
#   Directory for the tests that `deploy_pin task` creates. When not
#   set, the test framework's default is used (`spec/deploy_pin` for RSpec).
#   @param val [String, nil] new value; omit to read the current one
#   @return [String, nil]
#
# @!method self.tasks_path(val = nil)
#   Directory that holds task files.
#   @param val [String, nil] new value; omit to read the current one
#   @return [String, nil]
module DeployPin
  # Storage models are loaded lazily, so only the configured ORM has to be present.
  autoload :ApplicationRecord, 'deploy_pin/storage/active_record/application_record'
  autoload :Record, 'deploy_pin/storage/active_record/record'
  autoload :MongoidRecord, 'deploy_pin/storage/mongoid_record'

  # Names of the configuration options. Each one is a reader/writer method on {DeployPin}.
  OPTIONS = %i[
    continue_on_error
    deployment_state_transition
    fallback_group
    groups
    list_formatter
    short_list_formatter
    run_formatter
    statement_timeout
    storage
    task_wrapper
    tasks_path
    test_framework
    tests_path
  ].freeze

  # Values the options are reset to by {setup_defaults!}.
  DEFAULTS = {
    continue_on_error: false,
    storage: :active_record,
    task_wrapper: ->(_task, task_runner) { task_runner.call }
  }.freeze

  OPTIONS.each do |option|
    instance_eval %{
      def #{option}(val = nil)
        return @#{option} if val.nil?

        @#{option} = val
      end
    }, __FILE__, __LINE__ - 6
  end

  # Configures DeployPin. The block is evaluated on the {DeployPin} module, so
  # every option can be called without a receiver.
  #
  # @example
  #   DeployPin.setup do
  #     groups %w[I II III]
  #   end
  # @yield the configuration block
  # @return [void]
  def self.setup(&block)
    instance_eval(&block)
  end

  # Resets the options listed in {DEFAULTS} to their default values.
  #
  # @return [void]
  def self.setup_defaults!
    DEFAULTS.each do |option, value|
      instance_variable_set(:"@#{option}", value)
    end
  end

  setup_defaults!

  # Configuration files loaded by {load_config} when none is given: the one
  # `deploy_pin install` creates, then the Rails initializer.
  CONFIG_FILES = %w[config/deploy_pin.rb config/initializers/deploy_pin.rb].freeze

  # The rake file with the `deploy_pin:*` tasks.
  TASKS_FILE = File.expand_path('tasks/deploy_pin_tasks.rake', __dir__)

  # Defines the `deploy_pin:*` rake tasks. Rails apps get them from {Engine};
  # other apps call this from their Rakefile. The tasks are defined once per
  # Rake application: calling it again does not add their actions twice.
  #
  # The tasks first run the app's `environment` task when it is defined (load
  # the app and connect to the database there), else {load_config}.
  #
  # @example Rakefile
  #   require 'deploy_pin'
  #   DeployPin.load_tasks
  #
  #   task :environment do
  #     require_relative 'config/environment'
  #   end
  # @return [void]
  def self.load_tasks
    require 'rake'
    load TASKS_FILE
  end

  # Rake applications that have the `deploy_pin:*` tasks.
  RAKE_APPLICATIONS = ObjectSpace::WeakMap.new
  private_constant :RAKE_APPLICATIONS

  # Records that the `deploy_pin:*` tasks are being defined in a Rake
  # application. Called by {TASKS_FILE}, which {load_tasks} and the Rails
  # engine load.
  #
  # @api private
  # @param application [Rake::Application]
  # @return [Boolean] false if the application has the tasks already
  def self.register_rake_tasks(application = Rake.application)
    # Rake::Task.clear removes them: define them again then
    return false if RAKE_APPLICATIONS.key?(application) && application.lookup('deploy_pin:run')

    RAKE_APPLICATIONS[application] = true
  end

  # Loads the configuration: the given files, or else the first of
  # {CONFIG_FILES} that exists in `root`.
  #
  # @param files [Array<String>, String, nil] files to load, e.g. `config/environment.rb`
  # @param root [String] directory the files are relative to
  # @return [Array<String>] the loaded files
  # @raise [ArgumentError] if a given file does not exist
  def self.load_config(files = nil, root: Dir.pwd)
    paths = Array(files).map { |file| File.expand_path(file, root) }
    missing = paths.reject { |path| File.exist?(path) }
    raise ArgumentError, "No such file: #{missing.join(', ')}" if missing.any?

    paths = default_config_file(root) if paths.empty?
    paths.each { |path| require path }
  end

  # @param root [String] the app directory
  # @return [Array<String>] the first of {CONFIG_FILES} that exists in `root`, if any
  def self.default_config_file(root)
    CONFIG_FILES.map { |file| File.expand_path(file, root) }.select { |path| File.exist?(path) }.first(1)
  end

  # Whether an option has been set, even to `nil`.
  #
  # @param option [Symbol] one of {OPTIONS}
  # @return [Boolean]
  def self.enabled?(option)
    instance_variable_defined?("@#{option}")
  end
end
